def main() -> None:
    with open(TAROT_JSON, encoding="utf-8") as f:
        data = json.load(f)

    cards = data["tarot_interpretations"]
    updated = 0
    missing = []

    for card in cards:
        name = card["name"]
        if name in TRANSLATIONS:
            card["fortune_telling_ru"] = TRANSLATIONS[name]
            updated += 1
        else:
            missing.append(name)

    if missing:
        print(f"WARNING: No translation for: {missing}")

    with open(TAROT_JSON, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"Done. Updated {updated}/{len(cards)} cards.")
    print(f"Written to: {TAROT_JSON}")


if __name__ == "__main__":
    main()
