import re

# Improved Regex Components
_DRAW_PREFIX = (
    r"(?:"
    r"(?:привет|хай|здравствуй(?:те)?|hi|hello|здорово|слушай|окей|гм|хм)\s*[,:]?\s*"
    r"|(?:бот[аы]?|дружище|ассистент|нейронка)\s*[,:]?\s*"
    r"|(?:мне\s+)?(?:нужно|надо|хочу|хотим|можешь(?:\s+ты)?|будь\s+добр)\s*"
    r"|(?:пожалуйста|плиз|э+|м+|ну|а|так|ладно)\s*"
    r")*"
)

_DRAW_VERBS = (
    r"(?:"
    r"нарисуй|нарисуйте|рисуй|нарисовать|изобрази|изобразите|изобразить"
    r"|сгенерируй|сгенерируйте|сгенерировать"
    r"|сделай|создай|покажи|напиши|яви|выдай"
    r"|draw|generate|create|show|make"
    r")"
)

# Added common noise like "про", "на тему", etc.
_DRAW_POST_VERB = (
    r"(?:"
    r"\s+(?:мне|нам|для\s*мен[яе]|пожалуйста|плиз|э+|м+|ну|давай|ка|побыстрее)"
    r"|\s+(?:картинк[иуа]|изображени[ея]|фото(?:графи[ию])?|рисунк[иу]|иллюстраци[ию]|арт[ы]?)"
    r"|\s+(?:в\s*стиле|на\s*тему|по\s*запросу|про|о|об|на\s+котором|где\s+будет|с\s+участием)"
    r")*"
)

DRAW_TRIGGER_RE = re.compile(
    rf"^{_DRAW_PREFIX}{_DRAW_VERBS}{_DRAW_POST_VERB}[\s:]+(.+)$",
    re.IGNORECASE | re.DOTALL,
)

test_cases = [
    "Бот, сгенерируй мне картинки по такой теме: Космос",
    "Привет, бот, создай изображение, где будет Кот",
    "Слушай, нейронка, нарисуй-ка мне пожалуйста арты в стиле киберпанк город будущего",
    "нарисуй кота",
    "сделай фото леса",
    "Окей бот, я хочу чтобы ты изобразил нам на тему осени в Париже",
]

print("Testing combined triggers...")
for tc in test_cases:
    match = DRAW_TRIGGER_RE.match(tc.strip())
    if match:
        print(f"MATCH: '{tc}' -> '{match.group(1)}'")
    else:
        print(f"FAIL: '{tc}'")
